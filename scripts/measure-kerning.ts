/**
 * Measures the page titles' kerning (C55 D1). Page titles rise in letter by letter, and each letter
 * is its own box, so the browser can't kern between them. This opens the running site, sets text in
 * the h1's exact font (Bricolage at its title cut), and records how much each letter pair tightens
 * or loosens, in em. Letters.tsx applies it as each letter's right margin.
 *
 *   pnpm dev   # in another terminal
 *   pnpm exec tsx scripts/measure-kerning.ts http://localhost:3000
 */
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const base = process.argv[2] ?? 'http://localhost:3000';
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789&\'-.,:;!?/()"’';

async function main() {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto(`${base}/about`);
  await page.evaluate(() => document.fonts.ready);
  // A plain string: tsx would wrap a function's helpers in names the page doesn't have.
  const pairs = (await page.evaluate(`(() => {
    const chars = ${JSON.stringify(CHARS)};
    const style = getComputedStyle(document.querySelector('main header h1'));
    const size = 200;
    const probe = document.createElement('span');
    for (const prop of ['font-family', 'font-weight', 'font-variation-settings'])
      probe.style.setProperty(prop, style.getPropertyValue(prop));
    probe.style.cssText += ';position:absolute;white-space:pre;font-size:' + size + 'px;font-kerning:normal;font-variant-ligatures:none';
    document.body.append(probe);
    const width = (text) => { probe.textContent = text; return probe.getBoundingClientRect().width; };
    const single = new Map([...chars].map((c) => [c, width(c)]));
    const out = {};
    for (const a of chars)
      for (const b of chars) {
        const k = Math.round(((width(a + b) - single.get(a) - single.get(b)) / size) * 1000) / 1000;
        if (k !== 0) out[a + b] = k;
      }
    probe.remove();
    return out;
  })()`)) as Record<string, number>;
  await browser.close();

  const body = Object.entries(pairs)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([pair, k]) => `  ${JSON.stringify(pair)}: ${k},`)
    .join('\n');
  writeFileSync(
    'src/lib/kerning.ts',
    `// Generated by scripts/measure-kerning.ts from the page titles' font (C55 D1); do not edit by hand.\n` +
      `// Each pair's kerning in em: how much the second letter moves toward (negative) the first.\n` +
      `export const TITLE_KERNING: Readonly<Record<string, number>> = {\n${body}\n};\n`,
  );
  console.log(`${Object.keys(pairs).length} kerned pairs`);
}

void main();
